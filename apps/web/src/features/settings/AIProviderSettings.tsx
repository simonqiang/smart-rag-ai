import { useCallback, useEffect, useState } from "react";

import { detailText, getJson, postJson } from "../auth/api";

import "../../styles/settings.css";

type ProviderState = {
  provider: string;
  endpoint: string | null;
  model: string | null;
  rewrite_enabled: boolean;
  consent_version: string | null;
  consented_at: string | null;
  consent_version_current: string;
};

/** ISO timestamp -> "YYYY-MM-DD HH:MM" (deterministic, no locale drift); null -> "—". */
export function formatTime(iso: string | null): string {
  return iso ? `${iso.slice(0, 16).replace("T", " ")}` : "—";
}

/** One-line summary of the active generation provider, visible to every role. */
export function stateSummary(state: ProviderState): string {
  if (state.provider !== "glm") {
    return "Answers are generated locally by Ollama; nothing leaves this machine.";
  }
  const rewrite = state.rewrite_enabled ? "on" : "off";
  return (
    `Answers are generated by GLM at ${state.endpoint} using ${state.model} ` +
    `(hosted; query rewriting ${rewrite}). ` +
    `Consent version ${state.consent_version} accepted ${formatTime(state.consented_at)}.`
  );
}

export default function AIProviderSettings() {
  const [state, setState] = useState<ProviderState | null>(null);
  const [isOwner, setIsOwner] = useState(false);
  const [endpoint, setEndpoint] = useState("");
  const [model, setModel] = useState("");
  const [rewrite, setRewrite] = useState(false);
  const [consent, setConsent] = useState(false);
  // Test-before-activate: the probe must pass for the exact endpoint/model
  // currently in the form before Activate unlocks.
  const [tested, setTested] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const load = useCallback(async () => {
    setError(null);
    const result = await getJson("/api/settings/ai-provider");
    if (!result.ok) {
      setError(detailText(result));
      return;
    }
    setState(result.payload as unknown as ProviderState);
  }, []);

  useEffect(() => {
    void load();
    void getJson("/api/session").then((me) => {
      if (me.ok) setIsOwner(String(me.payload.role) === "owner");
    });
  }, [load]);

  async function testConnection(event: React.FormEvent) {
    event.preventDefault();
    setError(null);
    setNotice(null);
    setBusy(true);
    const result = await postJson("/api/settings/ai-provider/test", { endpoint, model });
    setBusy(false);
    if (!result.ok) {
      setError(detailText(result));
      return;
    }
    setTested(true);
    setNotice("Connection test passed. Review the consent text, then activate.");
  }

  async function activate() {
    setError(null);
    setNotice(null);
    setBusy(true);
    const result = await postJson("/api/settings/ai-provider/activate", {
      endpoint,
      model,
      rewrite_enabled: rewrite,
      consent_version: state?.consent_version_current ?? "",
    });
    setBusy(false);
    if (!result.ok) {
      setError(detailText(result));
      return;
    }
    setState(result.payload as unknown as ProviderState);
    setConsent(false);
    setTested(false);
    setNotice("GLM is now the generation provider. Embeddings are unchanged.");
  }

  async function revert() {
    setError(null);
    setNotice(null);
    setBusy(true);
    const result = await postJson("/api/settings/ai-provider/revert", {});
    setBusy(false);
    if (!result.ok) {
      setError(detailText(result));
      return;
    }
    setState(result.payload as unknown as ProviderState);
    setNotice("Reverted to local Ollama generation.");
  }

  const canActivate = tested && consent && endpoint.length > 0 && model.length > 0 && !busy;

  return (
    <main>
      <h1>AI provider</h1>
      {error && <p role="alert">{error}</p>}
      {notice && <p role="status">{notice}</p>}

      <section aria-labelledby="provider-state-heading">
        <h2 id="provider-state-heading">Current provider</h2>
        {state === null ? (
          <p role="status">Loading provider state…</p>
        ) : (
          <p data-testid="provider-summary" className="provider-summary">{stateSummary(state)}</p>
        )}
      </section>

      {isOwner && state !== null && (
        <section aria-labelledby="provider-form-heading">
          <h2 id="provider-form-heading">Switch generation to GLM</h2>
          <p>
            GLM is a hosted service: questions and up to four recent conversation
            messages are sent to the configured endpoint. The API key stays in the
            server environment (SMART_RAG_GLM_API_KEY) and is never stored here.
            Switching never re-indexes your knowledge.
          </p>
          <form onSubmit={testConnection} className="stack">
            <label>
              Endpoint URL
              <input
                type="url"
                required
                value={endpoint}
                onChange={(event) => {
                  setEndpoint(event.target.value);
                  setTested(false);
                }}
              />
            </label>
            <label>
              Model
              <input
                required
                value={model}
                onChange={(event) => {
                  setModel(event.target.value);
                  setTested(false);
                }}
              />
            </label>
            <label className="settings-check">
              <input
                type="checkbox"
                checked={rewrite}
                onChange={(event) => setRewrite(event.target.checked)}
              />{" "}
              Also use GLM to rewrite questions before retrieval
            </label>
            <label className="settings-check">
              <input
                type="checkbox"
                checked={consent}
                onChange={(event) => setConsent(event.target.checked)}
              />{" "}
              I accept the GLM data-processing terms (version{" "}
              {state.consent_version_current})
            </label>
            <button type="submit" disabled={busy || endpoint.length === 0 || model.length === 0}>
              Test connection
            </button>{" "}
            <button type="button" disabled={!canActivate} onClick={() => void activate()}>
              Activate GLM
            </button>
          </form>
        </section>
      )}

      {isOwner && state?.provider === "glm" && (
        <section aria-labelledby="provider-revert-heading">
          <h2 id="provider-revert-heading">Back to local</h2>
          <button type="button" disabled={busy} onClick={() => void revert()}>
            Revert to local Ollama
          </button>
        </section>
      )}
    </main>
  );
}
